  /* ── WHAT IS SHOWN AT A YEAR ────────────────────────────────────────────
     A place is drawn while the year sits inside its span. WITH `hi` NULL
     EVERYTHING IS DRAWN AND THE READOUT SAYS SO \u2014 1,746 at once is a smear,
     and a reader should be told that is what they are looking at rather than
     left to conclude the ground was that crowded.

     AND A PLACE WITH NO SPAN IS ALWAYS DRAWN. 705 of these carry no date,
     which is Pleiades not knowing rather than the place not existing. Hiding
     them at every year would be inventing an absence. */
  /* ── A PERIOD OVERLAPS A SPAN; A YEAR SAT INSIDE ONE ────────────────────
     The test is overlap, not containment. A place attested 550 BC to AD 300
     belongs to the Classical, Hellenistic AND Roman periods, and asking
     whether one year falls inside it would answer a question the register was
     never posed.

     AND A PLACE WITH NO SPAN IS ALWAYS DRAWN. 705 of 1,746 carry no date,
     which is Pleiades not knowing rather than the place not existing. Hiding
     them in every period would invent an absence. */
  function alive(r) {
    if (era.a === null) { return true; }
    if (r.from === null && r.until === null) { return true; }
    if (r.until !== null && r.until < era.a) { return false; }
    if (r.from !== null && r.from > era.b) { return false; }
    return true;
  }

  function draw() {
    if (!open || !rows) { return; }
    view.setAttribute('transform',
      'translate(' + TX.toFixed(2) + ' ' + TY.toFixed(2) + ') scale(' + K.toFixed(4) + ')');
    var iv = 1 / K;
    /* ── A LABEL IS NOT A MARK, AND MAY GROW ─────────────────────────────
       The rule that a mark does not get bigger is about CLAIMS: a pin means
       "here" at every scale, and swelling it would assert a size no register
       holds. A LABEL IS NOT A CLAIM ABOUT THE WORLD. It is text to read, and
       at ×1 it is 5 px because a thousand names are competing for the room.
       Zoom in and most of that competition leaves the screen, so the type can
       have the space it was denied.

       It grows on a LOGARITHM, not on K. Linear growth would put the marks
       back where the counter-scale took them from — 5 px at ×1 becoming 60 px
       at ×12 — and the surface would be a wall of type. This runs 5.0 px at ×1
       to about 8.6 px at ×12: legible, and still smaller than the list. */
    var TY = 5.0 * (1 + Math.log(Math.max(1, K)) * 0.22);
    var shown = rows.filter(alive);
    var pins = shown.filter(function (r) { return r.tier === 'pin'; });
    var wash = shown.filter(function (r) { return r.tier !== 'pin'; });

    /* washes first, and they are rectangles about their point because
       ATTICA.csv carries a representative coordinate rather than the bounding
       box. THAT IS A COMPROMISE AND IT IS STATED: the true extent is in
       Pleiades' bounding_box_wkt and is not harvested yet, so this draws a
       fixed soft area meaning "somewhere about here" rather than a false one
       meaning "exactly this rectangle". */
    var wh = '';
    wash.forEach(function (r) {
      var p = proj(r.lat, r.lon), a = 9 * iv;
      wh += '<rect class="at-wash" x="' + (p[0] - a).toFixed(2) + '" y="' + (p[1] - a).toFixed(2) +
            '" width="' + (a * 2).toFixed(2) + '" height="' + (a * 2).toFixed(2) +
            '" rx="' + (3 * iv).toFixed(2) + '" data-k="' + esc(r.key) + '"/>';
    });
    el.querySelector('.at-washes').innerHTML = wh;

    /* ── THE MARK HOLDS ITS SIZE AND SO DOES ITS OUTLINE ─────────────────
       Both divided by K, together. On 6 September the type was corrected and
       the outline was not, and at x14 a 0.23 px letter sat inside a 0.91 px
       stroke: every name on the world map drew as a black lozenge. The pair
       is one thing and moves as one. */
    var ph = '', placed = [], named = 0, dropped = 0, undated = 0;
    var tally = {};
    /* ── THE CULL RANKS BY CORROBORATION, THEN BY NEARNESS ────────────────
       Sorting by distance alone put the Acropolis' own gates first and Delphi
       nowhere, because the cull lays out greedily and the near ones take the
       room. THE CORPUS KNOWS WHICH PLACES CARRY THE STORY — Athens in 61
       reading rooms, Corinth in 27, Delphi in 24 — so a place named by many
       sources gets its label before a farmstead two hundred metres from the
       centre. Without the mentions file this falls back to distance, which is
       what it did before. */
    pins.sort(function (a, b) {
      var ma = mentions && mentions[a.key], mb = mentions && mentions[b.key];
      var sa = ma ? ma.src : 0, sb = mb ? mb.src : 0;
      if (sa !== sb) { return sb - sa; }
      return (+a.km) - (+b.km);
    });
    pins.forEach(function (r) {
      var p = proj(r.lat, r.lon);
      var fit = true, w = (r.name || '').length * (TY * 0.32) * iv;
      for (var i = 0; i < placed.length; i++) {
        if (Math.abs(p[0] - placed[i][0]) < (w + placed[i][2]) &&
            Math.abs(p[1] - placed[i][1]) < TY * 1.4 * iv) { fit = false; break; }
      }
      if (fit && K >= 1.8) { placed.push([p[0], p[1], w]); named++; } else { fit = false; dropped++; }
      var und = (r.from === null && r.until === null);
      if (und) { undated++; }
      var m = markOf(r.kind);
      tally[m] = (tally[m] || 0) + 1;
      if (offMarks[m]) { return; }
      var a = 1.9 * iv, d = shape(m, a);
      var body;
      if (d) {
        body = '<path class="at-pin at-m-' + m + '" d="' + d + '" transform="translate(' +
               p[0].toFixed(2) + ' ' + p[1].toFixed(2) + ')" data-k="' + esc(r.key) + '"/>';
      } else if (m === 'games') {
        body = '<ellipse class="at-pin at-m-games" cx="' + p[0].toFixed(2) + '" cy="' +
               p[1].toFixed(2) + '" rx="' + (a * 1.15).toFixed(2) + '" ry="' +
               (a * .68).toFixed(2) + '" data-k="' + esc(r.key) + '"/>';
      } else {
        body = '<circle class="at-pin at-m-' + m + '" cx="' + p[0].toFixed(2) + '" cy="' +
               p[1].toFixed(2) + '" r="' + (1.5 * iv).toFixed(2) + '" data-k="' + esc(r.key) + '"/>';
      }
      /* ── CORROBORATED IS BRIGHTER, AND IT IS NOT A SECOND KIND OF PLACE ──
         A place the corpus names is the same place; what changes is how much
         stands behind it. So the MARK does not change — a harbour is a
         crescent whether Thucydides mentions it or not — only its weight. Two
         sources or more and it holds full strength; the rest sit back. */
      var mn = mentions && mentions[r.key];
      ph += '<g class="at-seat at-' + m + (fit ? ' at-named' : '') +
            (und ? ' at-undated' : '') +
            (mn ? (mn.src > 1 ? ' at-cited' : ' at-mentioned') : '') +
            '" data-k="' + esc(r.key) + '">' + body +
            /* THE OUTLINE MOVES WITH THE TYPE. Sized from TY, not from a
               constant — the world map corrected its font on 6 September and
               left the stroke behind, and every name drew as a black lozenge
               at ×14. One pair, one number. */
            /* ── THE HALO ATE THE LETTER · found 7 Sep ────────────────────
               At 0.30 of the font the stroke is 2.3 px on a 7.7 px face, which
               is 1.15 px EACH SIDE of the glyph outline — and a monospace stem
               at that size is about 1 px wide. The outline met itself in the
               middle and every name drew solid dark: invisible on pale
               terrain, fine on the sea, which is why it looked like the labels
               were flipping colour as the map moved.

               THE WORLD MAP'S LOZENGE WAS THE SAME FAULT AT FOUR TIMES THE
               SCALE. Its ratio of 0.29 survived only because 5.6 px type has
               slightly fatter stems than 7.7 px type has room for. 0.17 leaves
               the stem clear at every size this surface draws. */
            (fit ? '<text class="at-name" x="' + p[0].toFixed(2) + '" y="' +
                   (p[1] - TY * 0.68 * iv).toFixed(2) + '" style="font-size:' +
                   (TY * iv).toFixed(3) + 'px;stroke-width:' +
                   (TY * 0.17 * iv).toFixed(3) + 'px">' +
                   esc(r.name) + '</text>' : '') +
            '</g>';
    });
    el.querySelector('.at-pins').innerHTML = ph;

    var cr = el.querySelector('.at-clockread');
    if (cr) {
      cr.textContent = scrub === null ? 'the whole period' : yr(scrub);
    }
    el.querySelector('.at-read').textContent =
      era.a === null ? 'the whole register' : era.label + '  \u00b7  ' + era.when;
    el.querySelector('.at-note').innerHTML =
      '<span class="at-warn at-first">Every shoreline here is TODAY\u2019S. ' +
      'Thermopylae\u2019s has moved six kilometres since 480 BC; Piraeus, Eleusis and ' +
      'Marathon are silted harbours.</span>' +
      shown.length + ' of ' + rows.length + ' places \u00b7 ' + pins.length + ' pinned \u00b7 ' +
      wash.length + ' somewhere in an area \u00b7 ' +
      /* NOTHING NAMED IS CORRECT AND LOOKS BROKEN. At x1 with the whole
         register on, every one of 1,567 labels collides and the cull drops
         them all \u2014 which is the right answer and reads as a fault. It says so. */
      (named ? named + ' named' : '<b>nothing named at this zoom</b> \u2014 every ' +
               'label collides; zoom past \u00d71.8') +
      (named && dropped ? ', ' + dropped + ' with no room' : '') +
      (undated ? ' \u00b7 <b>' + undated + ' undated</b>, drawn dim in every period: ' +
                 'Pleiades not knowing WHEN is not the place not existing' : '') +
      (era.a === null
        ? ' \u00b7 <b>all of it at once, which is a smear</b> \u2014 pick a period'
        : ' \u00b7 <b>five periods, not years</b> \u2014 \u201cClassical\u201d is dated ' +
          '550\u2013330 BC because a range needs a number, and most spans cross every ' +
          'period, so this filters less than it looks like it should') +
      (mentions
        ? ' \u00b7 <b>' + shown.filter(function (x) { return mentions[x.key]; }).length +
          ' named in the library</b>, of 603 texts and 35.9 M characters \u2014 ' +
          'labels go to the corroborated first'
        : (mentionsErr
            ? ' \u00b7 ATTICA-MENTIONS.csv not read (' + esc(mentionsErr) + '), so nothing ' +
              'here knows which places the corpus names'
            : '')) +
      (events ? ' \u00b7 <b>' + evn + ' event' + (evn === 1 ? '' : 's') +
                '</b> on the ground they happened on, authored' +
                (scrub !== null
                  ? ' \u00b7 <b>the year moves the events only</b> \u2014 a place here is ' +
                    'dated to a PERIOD, so scrubbing cannot move it and pretending ' +
                    'otherwise would animate a register that is standing still'
                  : '') : '') +
      ' \u00b7 Pleiades CC BY 3.0 \u00b7 land 30 m Copernicus, sea 462 m ETOPO.';

    /* ── THE EVENTS, ON THE GROUND THEY HAPPENED ON ──────────────────────
       An event belongs to a period if its year sits INSIDE it — a containment
       test, and correct here unlike the places, whose spans are period bands
       and are tested by overlap. A moment has a year; a place has a stretch of
       centuries, and asking the same question of both would be wrong twice. */
    var eg = el.querySelector('.at-events'), eh = '', evn = 0;
    if (eg) {
      if (events) {
        events.forEach(function (v) {
          if (era.a !== null && (v.year < era.a || v.year > era.b)) { return; }
          /* ── IT FADES WITH DISTANCE IN YEARS, IT DOES NOT VANISH ─────────
             At the scrubbed year an event is at full strength; forty years
             either side it is a trace. It is never hidden, because a reader
             moving through time should see what is coming and what has just
             passed — and because a mark that blinks out asserts that nothing
             happened, which is a claim about silence the register cannot
             make. */
          var d = scrub === null ? 0 : Math.abs(v.year - scrub);
          var glow = scrub === null ? 1 : Math.max(0.1, 1 - d / FADE);
          evn++;
          var p = proj(v.lat, v.lon), a = 3.4 * iv * (0.75 + 0.45 * glow);
          var d = 'M0 ' + (-a).toFixed(2) + 'v' + (a * 0.55).toFixed(2) +
                  'M0 ' + a.toFixed(2) + 'v' + (-a * 0.55).toFixed(2) +
                  'M' + (-a).toFixed(2) + ' 0h' + (a * 0.55).toFixed(2) +
                  'M' + a.toFixed(2) + ' 0h' + (-a * 0.55).toFixed(2);
          eh += '<g class="at-evg" data-e="' + esc(v.name) + '" style="opacity:' +
                (0.22 + 0.78 * glow).toFixed(3) + '">' +
                '<circle class="at-ev' + (v.at ? '' : ' at-ev-loose') + '" cx="' +
                p[0].toFixed(2) + '" cy="' + p[1].toFixed(2) + '" r="' +
                (a * 0.62).toFixed(2) + '"/>' +
                '<path class="at-ev" transform="translate(' + p[0].toFixed(2) + ' ' +
                p[1].toFixed(2) + ')" d="' + d + '"/>' +
                (K >= 2.2 || glow > 0.75
                  ? '<text class="at-evname" x="' + p[0].toFixed(2) + '" y="' +
                    (p[1] + TY * 1.6 * iv).toFixed(2) + '" style="font-size:' +
                    (TY * 0.92 * iv).toFixed(3) + 'px;stroke-width:' +
                    (TY * 0.17 * iv).toFixed(3) + 'px">' + esc(v.name) + '</text>'
                  : '') +
                '</g>';
        });
      }
      eg.innerHTML = eh;
    }

    /* the ring is redrawn with the frame so it stays on its place through a
       pan or a zoom — it is a pointer, and a pointer that lags is worse than
       none */
    haloAt(litKey);

    /* THE KEY DRAWS ITS SWATCHES WITH THE SAME shape() THE MAP USES. Two
       drawings of one mark would drift the first time either changed, and a
       legend that disagrees with the surface is worse than none. */
    var key = el.querySelector('.at-key');
    if (key && !key._built) {
      key._built = true;
      key.innerHTML = KEY.map(function (o) {
        var d = shape(o.k, 5);
        var body = d
          ? '<path d="' + d + '" fill="none" stroke="currentColor" stroke-width="1.2" ' +
            'stroke-linejoin="round" stroke-linecap="round" transform="translate(6.5 6.5)"/>'
          : (o.k === 'games'
              ? '<ellipse cx="6.5" cy="6.5" rx="5.8" ry="3.4" fill="none" ' +
                'stroke="currentColor" stroke-width="1.2"/>'
              : '<circle cx="6.5" cy="6.5" r="3" fill="currentColor"/>');
        return '<div data-m="' + o.k + '" aria-pressed="true" title="' + esc(o.eg) + '">' +
               '<svg viewBox="0 0 13 13">' + body + '</svg>' + o.label +
               '<b data-n="' + o.k + '"></b></div>';
      }).join('');
      key.addEventListener('click', function (e) {
        var d = e.target.closest ? e.target.closest('[data-m]') : null;
        if (!d) { return; }
        var m = d.getAttribute('data-m');
        if (offMarks[m]) { delete offMarks[m]; } else { offMarks[m] = 1; }
        d.setAttribute('aria-pressed', offMarks[m] ? 'false' : 'true');
        draw();
      });
    }
    if (key) {
      KEY.forEach(function (o) {
        var b = key.querySelector('b[data-n="' + o.k + '"]');
        if (b) { b.textContent = tally[o.k] || 0; }
      });
    }

    var lh = el.querySelector('.at-listhead');
    if (lh) {
      lh.textContent = (mentions ? 'most named first' : 'nearest first') +
        ' \u00b7 ' + pins.length + ' pinned, ' + wash.length + ' area' +
        (wash.length === 1 ? '' : 's');
    }
    /* ── THE MOST-NAMED PLACE WAS MISSING FROM THE LIST OF MOST-NAMED ─────
       The column showed pins only, and `Athenae` is a WASH — Pleiades records
       the city as an area rather than a point, which is correct and is why it
       has no dot. So Athens, named in 61 reading rooms against Corinth's 27,
       did not appear at all, and a reader scanning for it would conclude the
       corpus is silent on Athens.

       An area is not a lesser place. It is listed with everything else and
       says what it is, because THAT IT IS AN AREA IS INFORMATION AND NOT A
       REASON TO HIDE IT. The mark still differs on the map; only the ranking
       stops caring. */
    var listed = shown.slice().sort(function (a, b) {
      var ma = mentions && mentions[a.key], mb = mentions && mentions[b.key];
      var sa = ma ? ma.src : 0, sb = mb ? mb.src : 0;
      if (sa !== sb) { return sb - sa; }
      return (+a.km) - (+b.km);
    });

    var lb = el.querySelector('.at-list');
    lb.innerHTML = listed.slice(0, 90).map(function (r) {
      var mn = mentions && mentions[r.key];
      var isWash = r.tier !== 'pin';
      return '<div class="at-li' + (mn && mn.src > 1 ? ' at-licited' : '') +
             (isWash ? ' at-liwash' : '') +
             '" data-k="' + esc(r.key) + '" title="' +
             (isWash ? 'somewhere in this area \u2014 no single position' : '') + '">' +
             esc(r.name) + (isWash ? ' <i>\u25ad</i>' : '') +
             ' <span>' + (mn ? mn.src + ' room' + (mn.src === 1 ? '' : 's')
                             : r.km + ' km') + '</span></div>';
    }).join('') || '<div class="at-li">nothing in this year</div>';
  }

