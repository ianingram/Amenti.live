/* ============================================================================
   amenti-attica.js  ·  ATTICA — the first place
   ----------------------------------------------------------------------------
   A hundred miles from the Acropolis, at 39 metres a pixel. Marathon, Salamis,
   Thermopylae, Plataea, Delphi, Corinth, Sparta and Mycenae in one frame, on
   ground measured rather than drawn.

   ── IT IS A SECOND SURFACE, NOT A ZOOM OF THE FIRST ───────────────────────
   The world map answers WHERE AT THE SCALE OF A LIFE: a soul was born at a
   city, an event happened at a place. Every one of those resolves to a
   coordinate and a year and nothing finer, and at 40 km a pixel that is the
   right instrument.

   THIS ANSWERS A DIFFERENT QUESTION. Ninety Athenian demes. Twenty-four ports.
   Twenty-three named gates in the Themistoclean wall. At world scale all of
   that is one dot; here it is a landscape, and the ground is the explanation
   rather than the backdrop.

   So it takes the screen the way the map does, on its own scene class, with
   its own projection and its own camera. It does not zoom the world map and it
   does not edit it.

   ── A MODULE, AND IT STAYS ONE ────────────────────────────────────────────
   One script tag in hall.html and NO EDIT TO amenti-map.js. It joins the
   faculty rail through AmentiMap.addFaculty, beside the globe, the glass, the
   gates and the ground.

   On 6-7 September five reasoned changes to the map file each had to be
   reverted. Every instrument built since has been a module, and not one has
   been able to take the map down. This is the fifth.

   ── WHAT IT READS ─────────────────────────────────────────────────────────
       ATTICA.jpg   8192 x 8191 · land at 30 m from Copernicus, sea at 462 m
                    from ETOPO · generated by tools/render-attica.py
       ATTICA.csv   1,746 places from Pleiades · CC BY 3.0 · a URI per row

   Both are optional in the sense that failing to load one is stated rather
   than fatal: ground without places is a chart, places without ground is a
   constellation, and either is better than a blank surface with no reason
   given.

   ── THE ONE LAW COMES WITH IT ─────────────────────────────────────────────
   A PIN AND A WASH MUST NEVER BE MISTAKEN FOR ONE ANOTHER — and here the
   distinction is not this ship's judgement. Pleiades marks its own locations
   `precise` or `rough`, where rough means THE BOUNDS WITHIN WHICH THE FEATURE
   SHOULD BE SOUGHT. Classicists arrived at the same rule independently, and it
   is carried through rather than re-derived. 1,567 pin, 179 wash.

   ── AND THE SHORELINE IS MODERN, WHICH IS A CLAIM ─────────────────────────
   Every coast in ATTICA.jpg is today's. Thermopylae's has moved six kilometres
   since 480 BC, measured on this same ground; Piraeus, Eleusis and Marathon
   are all silted harbours. The terrain is the baseline because it is complete
   and free, NOT because it is contemporary with anything drawn on it. The
   surface says so where a reader will see it.
   ========================================================================== */
