  /* ── READING THE REGISTER ───────────────────────────────────────────────
     ATTICA.csv is written by tools/harvest-attica.py and quotes any field
     holding a comma, so the parse respects quotes rather than splitting on
     every comma \u2014 the fault that broke SEATS.csv on 6 September, where 25 rows
     gained a column because a note held a comma inside single quotes. */
  function parse(text) {
    var lines = String(text).replace(/\r\n/g, '\n').split('\n');
    var cols = split(lines[0]), out = [];
    for (var i = 1; i < lines.length; i++) {
      if (!lines[i].trim()) continue;
      var c = split(lines[i]), o = {};
      for (var j = 0; j < cols.length; j++) o[cols[j]] = c[j] == null ? '' : c[j];
      o.lat = +o.lat; o.lon = +o.lon;
      o.from = o.from === '' ? null : +o.from;
      o.until = o.until === '' ? null : +o.until;
      if (!isNaN(o.lat) && !isNaN(o.lon)) out.push(o);
    }
    return out;
  }
  function split(line) {
    var c = [], cur = '', q = false;
    for (var i = 0; i < line.length; i++) {
      var ch = line[i];
      if (ch === '"') { q = !q; continue; }
      if (ch === ',' && !q) { c.push(cur); cur = ''; continue; }
      cur += ch;
    }
    c.push(cur);
    return c;
  }

